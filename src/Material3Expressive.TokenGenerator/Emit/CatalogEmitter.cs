using System;
using System.Collections.Generic;
using System.Linq;
using Material3Expressive.TokenGenerator.Model;

namespace Material3Expressive.TokenGenerator.Emit;

/// <summary>Emits the immutable M3E-owned portion of the composed Raw-token default graph.</summary>
internal static class CatalogEmitter
{
    public const string HintName = "GeneratedM3DefaultRawTokens.g.cs";

    public static string Emit(IReadOnlyList<TokenTable> tables, ExternalCanonicalManifest manifest)
    {
        var tokenTables = tables
            .Where(static table => table.IsTokenSet)
            .OrderBy(static table => table.Name, StringComparer.Ordinal)
            .ThenBy(static table => table.Namespace, StringComparer.Ordinal)
            .ToArray();
        var byName = tokenTables.ToDictionary(static table => table.Name, StringComparer.Ordinal);

        var writer = new CodeWriter();
        writer.Line("// <auto-generated />");
        writer.Line("// Generated by Material3Expressive.TokenGenerator from the complete validated Raw token graph.");
        writer.Line($"// External canonical owner: {manifest.Owner}");
        writer.Line($"// Required contribution: {manifest.ContributionId} schema {manifest.ContributionSchemaVersion}");
        writer.Line("#nullable enable");
        writer.Line();
        writer.Line("namespace Material3Expressive.Foundation.Tokens;");
        writer.Line();
        writer.Doc("summary", "Generated immutable baseline definitions for all M3E-owned Raw tokens.");
        using (writer.Block(
                   "internal sealed class GeneratedM3DefaultRawTokens : " +
                   "global::MaterialDesignTokens.Avalonia.IMaterialTokenCatalogContribution"))
        {
            writer.Line(
                "private static readonly global::System.Collections.Generic.IReadOnlyList<" +
                "global::MaterialDesignTokens.Avalonia.MaterialTokenCatalogRequirement> RequiredContributions = " +
                "global::System.Array.AsReadOnly(new[]");
            using (writer.Block(string.Empty, "});"))
            {
                writer.Line(
                    "new global::MaterialDesignTokens.Avalonia.MaterialTokenCatalogRequirement(" +
                    $"\"{manifest.ContributionId}\", {manifest.ContributionSchemaVersion}, {manifest.ContributionSchemaVersion})");
            }

            writer.Line();
            writer.Line(
                "private readonly global::System.Collections.Generic.IReadOnlyDictionary<" +
                "global::MaterialDesignTokens.Avalonia.MaterialToken, " +
                "global::MaterialDesignTokens.Avalonia.TokenDefinition> _definitions;");
            writer.Line(
                "private readonly global::System.Collections.Generic.IReadOnlyCollection<" +
                "global::MaterialDesignTokens.Avalonia.MaterialToken> _declaredTokens;");
            writer.Line();
            writer.Line(
                "private static global::MaterialDesignTokens.Avalonia.TokenDefinition<global::Avalonia.Media.Color> " +
                "ExternalColorAlias(global::MaterialDesignTokens.Avalonia.MaterialToken<global::Avalonia.Media.Color> target) => " +
                "global::MaterialDesignTokens.Avalonia.Token.Alias(target);");
            writer.Line();
            using (writer.Block("private GeneratedM3DefaultRawTokens()"))
            {
                writer.Line(
                    "var definitions = new global::System.Collections.Generic.Dictionary<" +
                    "global::MaterialDesignTokens.Avalonia.MaterialToken, " +
                    "global::MaterialDesignTokens.Avalonia.TokenDefinition>();");

                foreach (var table in tokenTables)
                {
                    foreach (var token in table.Tokens.OrderBy(static token => token.Name, StringComparer.Ordinal))
                    {
                        writer.Line(
                            $"definitions.Add({Key(table, token.Name)}, " +
                            $"{Definition(token, manifest, byName)});");
                    }
                }

                writer.Line("_definitions = definitions;");
                writer.Line(
                    "_declaredTokens = global::System.Array.AsReadOnly(" +
                    "global::System.Linq.Enumerable.ToArray(definitions.Keys));");
            }

            writer.Line();
            writer.Doc("summary", "Gets the singleton generated M3E contribution.");
            writer.Line("public static GeneratedM3DefaultRawTokens Instance { get; } = new();");
            writer.Line();
            writer.Line("public string Id => \"Material3Expressive.GeneratedM3DefaultRawTokens\";");
            writer.Line("public int SchemaVersion => 1;");
            writer.Line(
                "public global::System.Collections.Generic.IReadOnlyList<" +
                "global::MaterialDesignTokens.Avalonia.MaterialTokenCatalogRequirement> Requirements => RequiredContributions;");
            writer.Line(
                "public global::System.Collections.Generic.IReadOnlyCollection<" +
                "global::MaterialDesignTokens.Avalonia.MaterialToken> DeclaredTokens => _declaredTokens;");
            writer.Line(
                "public global::System.Collections.Generic.IReadOnlyCollection<" +
                "global::MaterialDesignTokens.Avalonia.MaterialTokenFamilyOwnership> DeclaredFamilies => " +
                "global::System.Array.Empty<global::MaterialDesignTokens.Avalonia.MaterialTokenFamilyOwnership>();");
            writer.Line();
            using (writer.Block("public bool Owns(global::MaterialDesignTokens.Avalonia.MaterialToken token)"))
            {
                writer.Line("if (token is null) throw new global::System.ArgumentNullException(nameof(token));");
                writer.Line("return _definitions.ContainsKey(token);");
            }

            writer.Line();
            using (writer.Block(
                       "public global::MaterialDesignTokens.Avalonia.MaterialTokenMissingPolicy GetMissingPolicy(" +
                       "global::MaterialDesignTokens.Avalonia.MaterialToken token)"))
            {
                writer.Line("if (!Owns(token)) throw new global::System.ArgumentException(\"The token is not owned by this contribution.\", nameof(token));");
                writer.Line("return global::MaterialDesignTokens.Avalonia.MaterialTokenMissingPolicy.CatalogRequired;");
            }

            writer.Line();
            using (writer.Block(
                       "public bool TryGetDefinition(global::MaterialDesignTokens.Avalonia.MaterialToken token, " +
                       "global::Avalonia.Styling.ThemeVariant? queryTheme, " +
                       "out global::MaterialDesignTokens.Avalonia.TokenDefinition? definition)"))
            {
                writer.Line("if (token is null) throw new global::System.ArgumentNullException(nameof(token));");
                writer.Line("return _definitions.TryGetValue(token, out definition);");
            }
        }

        return writer.ToString();
    }

    private static string Definition(
        TokenEntry token,
        ExternalCanonicalManifest manifest,
        IReadOnlyDictionary<string, TokenTable> byName)
    {
        const string factory = "global::MaterialDesignTokens.Avalonia.Token";
        if (token.Value.Reference is { } reference)
        {
            var target = byName[reference.TableName];
            return $"{factory}.Alias({Key(target, reference.MemberName)})";
        }

        if (token.Value.ColorRole is { } colorRole)
        {
            if (!manifest.TryResolve(colorRole, out var external))
                throw new InvalidOperationException($"Unvalidated external role '{colorRole.Role}'.");
            return $"ExternalColorAlias({external.EmitCanonicalReference(colorRole.CustomName)})";
        }

        if (token.Type == TokenType.Color)
        {
            const string prefix = "global::Material3Expressive.Foundation.ColorTokenValue.Literal(";
            var expression = token.Expression;
            if (!expression.StartsWith(prefix, StringComparison.Ordinal) ||
                !expression.EndsWith(")", StringComparison.Ordinal))
                throw new InvalidOperationException($"Unvalidated color expression for '{token.Name}'.");
            expression = expression.Substring(prefix.Length, expression.Length - prefix.Length - 1);
            return $"{factory}.Literal({expression})";
        }

        var literal = token.Type is TokenType.Dimension or TokenType.Number
            ? $"(double){token.Expression}"
            : token.Expression;
        return $"{factory}.Literal({literal})";
    }

    private static string Key(TokenTable table, string tokenName)
    {
        return $"global::{table.Namespace}.{table.Name}Keys.{tokenName}";
    }
}
