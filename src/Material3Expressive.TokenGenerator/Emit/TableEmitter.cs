using System;
using System.Collections.Generic;
using System.Linq;
using Material3Expressive.TokenGenerator.Model;

namespace Material3Expressive.TokenGenerator.Emit;

/// <summary>
/// Turns token tables into C#.
/// </summary>
/// <remarks>
/// The generated shape mirrors upstream's own split: a <c>tokenSet</c> becomes the equivalent of an
/// <c>internal object *Tokens</c> — a verbatim transcription of the token DB — and a
/// <c>component</c> table becomes the value record those transcriptions are composed into, one
/// instance per variant, plus the sparse authoring bag that lets a theme override individual
/// tokens.
/// </remarks>
internal static class TableEmitter
{
    private const string BrushType = "global::Avalonia.Media.IImmutableBrush";
    private const string SchemeType = "global::MaterialColorUtilities.Avalonia.Tokens.ResolvedColorScheme";
    private const string OverridesBase = "global::Material3Expressive.Foundation.ComponentTokenOverrides";

    public static string Emit(TokenTable table)
    {
        var writer = new CodeWriter();
        Header(writer, table);

        writer.Line($"namespace {table.Namespace};");
        writer.Line();

        if (table.Kind == "tokenSet")
            TokenSet(writer, table);
        else
            Component(writer, table);

        return writer.ToString();
    }

    /// <summary>
    /// The one file that knows about every component table: the theme snapshot's accessors and the
    /// single pass that layers the theme's overrides onto the generated defaults.
    /// </summary>
    public static string EmitThemeAccessors(IReadOnlyList<TokenTable> tables)
    {
        var components = tables.Where(t => t.Kind == "component").ToArray();

        var writer = new CodeWriter();
        writer.Line("// <auto-generated />");
        writer.Line("// Generated from the token tables by Material3Expressive.TokenGenerator.");
        writer.Line("#nullable enable");
        writer.Line();
        writer.Line("namespace Material3Expressive.Foundation;");
        writer.Line();

        writer.Doc("summary", "The generated half of the theme snapshot: one accessor per component token domain.");
        using (writer.Block("public sealed partial class ResolvedTheme"))
        {
            foreach (var table in components)
            {
                var field = Camel(table.Name);
                writer.Line($"private {Global(table)}[] _{field} = global::System.Array.Empty<{Global(table)}>();");

                if (table.ResolvedName is { } resolved)
                    writer.Line($"private {ResolvedGlobal(table, resolved)}?[] _{field}Brushes = " +
                                $"global::System.Array.Empty<{ResolvedGlobal(table, resolved)}?>();");
            }

            if (components.Length > 0)
                writer.Line();

            foreach (var table in components)
                ThemeAccessors(writer, table);

            writer.Doc("summary",
                "Builds every component token domain from the authoring theme. Called once from the snapshot's constructor, which is why the backing fields cannot be readonly.");
            using (writer.Block("private void InitializeComponentTokens(MaterialTheme theme)"))
            {
                foreach (var table in components)
                {
                    var field = Camel(table.Name);
                    var sets = table.Sets.Select(s => $"{Global(table)}.{s.Name}");
                    writer.Line($"_{field} = new[] {{ {string.Join(", ", sets)} }};");

                    if (table.ResolvedName is { } resolved)
                        writer.Line(
                            $"_{field}Brushes = new {ResolvedGlobal(table, resolved)}?[{table.Sets.Count * 2}];");
                }

                var overridable = components.Where(t => t.Overridable).ToArray();

                if (overridable.Length == 0)
                {
                    // Keep the parameter used so the signature stays stable across table sets.
                    writer.Line("_ = theme;");
                }
                else
                {
                    writer.Line();
                    using (writer.Block("foreach (var overrides in theme.Components)"))
                    using (writer.Block("switch (overrides)"))
                    {
                        foreach (var table in overridable)
                        {
                            var field = Camel(table.Name);
                            var slot = table.VariantEnum is { } ? "(int)typed.Variant" : "0";

                            writer.Line($"case {OverridesGlobal(table)} typed:");
                            using (writer.Indent())
                            {
                                writer.Line($"_{field}[{slot}] = typed.ApplyTo(_{field}[{slot}]);");
                                writer.Line("break;");
                            }
                        }
                    }
                }
            }
        }

        return writer.ToString();
    }

    private static void ThemeAccessors(CodeWriter writer, TokenTable table)
    {
        var field = Camel(table.Name);

        if (table.VariantEnum is { } variantEnum)
        {
            var enumType = $"global::{table.Namespace}.{variantEnum}";
            var parameter = Camel(variantEnum);

            writer.Doc("summary", $"The {table.Name} for one {variantEnum}, after the theme's overrides.");
            writer.Line(
                $"public {Global(table)} Get{table.Name}({enumType} {parameter}) => _{field}[(int){parameter}];");
            writer.Line();

            if (table.ResolvedName is { } resolved)
            {
                writer.Doc("summary",
                    $"The {table.Name} for one {variantEnum} and theme variant, resolved to brushes and memoised per snapshot.");
                using (writer.Block(
                           $"public {ResolvedGlobal(table, resolved)} Get{resolved}({enumType} {parameter}, bool isDark)"))
                {
                    writer.Line($"var slot = (int){parameter} * 2 + (isDark ? 1 : 0);");
                    writer.Line(
                        $"return _{field}Brushes[slot] ??= _{field}[(int){parameter}].Resolve(ColorScheme, isDark);");
                }

                writer.Line();
            }

            return;
        }

        writer.Doc("summary", $"The {table.Name}, after the theme's overrides.");
        writer.Line($"public {Global(table)} {table.Name} => _{field}[0];");
        writer.Line();

        if (table.ResolvedName is { } single)
        {
            writer.Doc("summary", $"The {table.Name} resolved to brushes for one theme variant, memoised per snapshot.");
            using (writer.Block($"public {ResolvedGlobal(table, single)} Get{single}(bool isDark)"))
            {
                writer.Line("var slot = isDark ? 1 : 0;");
                writer.Line($"return _{field}Brushes[slot] ??= _{field}[0].Resolve(ColorScheme, isDark);");
            }

            writer.Line();
        }
    }

    private static void Header(CodeWriter writer, TokenTable table)
    {
        writer.Line("// <auto-generated />");
        writer.Line($"// Generated from the {table.Name} token table by Material3Expressive.TokenGenerator.");

        if (table.Source is { } source)
            writer.Line($"// Source: {source}");

        if (table.Version is { } version)
            writer.Line($"// Token DB: {version}");

        writer.Line("#nullable enable");
        writer.Line();
    }

    private static void TokenSet(CodeWriter writer, TokenTable table)
    {
        writer.Doc("summary", table.Summary ?? $"The {table.Name} token set.");
        Provenance(writer, table);

        using (writer.Block($"public static class {table.Name}"))
        {
            var first = true;
            foreach (var token in table.Tokens)
            {
                if (!first)
                    writer.Line();

                first = false;

                writer.Doc("summary", token.Summary);
                var modifier = TokenTypes.IsConstant(token.Type) ? "const" : "static readonly";
                writer.Line($"public {modifier} {TokenTypes.ToClrType(token.Type, token.EnumType)} {token.Name} = {token.Expression};");
            }
        }
    }

    private static void Component(CodeWriter writer, TokenTable table)
    {
        if (table.VariantEnum is { } variantEnum)
        {
            writer.Doc("summary", table.VariantEnumSummary ?? $"The variants {table.Name} is defined for.");
            using (writer.Block($"public enum {variantEnum}"))
            {
                for (var i = 0; i < table.Sets.Count; i++)
                {
                    var set = table.Sets[i];
                    writer.Doc("summary", set.Summary);
                    writer.Line(i == table.Sets.Count - 1 ? set.Name : set.Name + ",");
                }
            }

            writer.Line();
        }

        ValueRecord(writer, table);

        if (table.ResolvedName is { } resolved)
        {
            writer.Line();
            BrushRecord(writer, table, resolved);
        }

        if (table.Overridable)
        {
            writer.Line();
            OverridesClass(writer, table);
        }
    }

    private static void ValueRecord(CodeWriter writer, TokenTable table)
    {
        writer.Doc("summary", table.Summary ?? $"The {table.Name} token values.");
        Provenance(writer, table);

        writer.Line($"public sealed partial record {table.Name}(");
        using (writer.Indent())
        {
            for (var i = 0; i < table.Properties.Count; i++)
            {
                var property = table.Properties[i];
                var comma = i == table.Properties.Count - 1 ? string.Empty : ",";
                writer.Line($"{TokenTypes.ToClrType(property.Type, property.EnumType)} {property.Name}{comma}");
            }
        }

        writer.Line(")");
        using (writer.Block(string.Empty))
        {
            for (var i = 0; i < table.Sets.Count; i++)
            {
                var set = table.Sets[i];
                if (i > 0)
                    writer.Line();

                writer.Doc("summary", set.Summary ?? $"The {set.Name} {table.Name}.");
                writer.Line($"public static {table.Name} {set.Name} {{ get; }} = new(");
                using (writer.Indent())
                {
                    for (var p = 0; p < table.Properties.Count; p++)
                    {
                        var property = table.Properties[p];
                        var comma = p == table.Properties.Count - 1 ? ");" : ",";
                        writer.Line($"{set.Values[property.Name]}{comma}");
                    }
                }
            }

            if (table.VariantEnum is { } variantEnum)
            {
                writer.Line();
                writer.Doc("summary", "The token values for one variant.");
                using (writer.Block($"public static {table.Name} For({variantEnum} variant)"))
                {
                    writer.Line("return variant switch");
                    using (writer.Block(string.Empty, "};"))
                    {
                        foreach (var set in table.Sets)
                            writer.Line($"{variantEnum}.{set.Name} => {set.Name},");

                        writer.Line($"_ => {table.Sets[0].Name}");
                    }
                }
            }

            if (table.ResolvedName is { } resolved)
            {
                writer.Line();
                writer.Doc("summary",
                    "Resolves every colour token against a scheme and theme variant. Callers should prefer the theme snapshot's memoised accessor.");
                writer.Line($"public {resolved} Resolve({SchemeType}? scheme, bool isDark)");
                using (writer.Indent())
                {
                    writer.Line("=> new(");
                    using (writer.Indent())
                    {
                        var colors = table.ColorProperties;
                        for (var i = 0; i < colors.Count; i++)
                        {
                            var property = colors[i];
                            var opacity = property.OpacityProperty is { } o ? $", {o}" : string.Empty;
                            var comma = i == colors.Count - 1 ? ");" : ",";
                            writer.Line($"{property.Name}.ResolveBrush(scheme, isDark{opacity}){comma}");
                        }
                    }
                }
            }
        }
    }

    private static void BrushRecord(CodeWriter writer, TokenTable table, string resolved)
    {
        writer.Doc("summary", $"{table.Name}' colour tokens resolved to brushes for one theme variant.");
        writer.Line($"public sealed record {resolved}(");
        using (writer.Indent())
        {
            var colors = table.ColorProperties;
            for (var i = 0; i < colors.Count; i++)
            {
                var comma = i == colors.Count - 1 ? string.Empty : ",";
                writer.Line($"{BrushType} {colors[i].Name}{comma}");
            }
        }

        writer.Line(");");
    }

    private static void OverridesClass(CodeWriter writer, TokenTable table)
    {
        var name = OverridesName(table);

        writer.Doc("summary", $"Theme-level overrides for {table.Name}.");
        writer.Doc("remarks",
            "Sparse: only the tokens actually set here replace the generated defaults, so an app can retune one colour without restating the set.");

        using (writer.Block($"public sealed partial class {name} : {OverridesBase}"))
        {
            if (table.VariantEnum is { } variantEnum)
            {
                writer.Doc("summary", "Which variant these overrides apply to.");
                writer.Line(
                    $"public static readonly global::Avalonia.StyledProperty<{variantEnum}> VariantProperty =");
                using (writer.Indent())
                    writer.Line(
                        $"global::Avalonia.AvaloniaProperty.Register<{name}, {variantEnum}>(nameof(Variant));");
                writer.Line();
                writer.Line($"public {variantEnum} Variant");
                using (writer.Block(string.Empty))
                {
                    writer.Line("get => GetValue(VariantProperty);");
                    writer.Line("set => SetValue(VariantProperty, value);");
                }

                writer.Line();
            }

            foreach (var property in table.Properties)
            {
                var type = TokenTypes.ToClrType(property.Type, property.EnumType);

                writer.Doc("summary", property.Summary);
                writer.Line($"public static readonly global::Avalonia.StyledProperty<{type}> {property.Name}Property =");
                using (writer.Indent())
                    writer.Line(
                        $"global::Avalonia.AvaloniaProperty.Register<{name}, {type}>(nameof({property.Name}));");
                writer.Line();
                writer.Doc("summary", property.Summary);
                writer.Line($"public {type} {property.Name}");
                using (writer.Block(string.Empty))
                {
                    writer.Line($"get => GetValue({property.Name}Property);");
                    writer.Line($"set => SetValue({property.Name}Property, value);");
                }

                writer.Line();
            }

            writer.Doc("summary", "Applies whichever tokens are set here onto a base set.");
            writer.Line($"public {table.Name} ApplyTo({table.Name} baseTokens)");
            using (writer.Indent())
            {
                writer.Line("=> new(");
                using (writer.Indent())
                {
                    for (var i = 0; i < table.Properties.Count; i++)
                    {
                        var property = table.Properties[i];
                        var comma = i == table.Properties.Count - 1 ? ");" : ",";
                        writer.Line(
                            $"IsSet({property.Name}Property) ? {property.Name} : baseTokens.{property.Name}{comma}");
                    }
                }
            }
        }
    }

    private static void Provenance(CodeWriter writer, TokenTable table)
    {
        if (table.Source is null && table.Version is null)
            return;

        var source = table.Source is { } s ? $"Transcribed from {s}" : "Transcribed from androidx";
        var version = table.Version is { } v ? $", token-DB stamp <c>{v}</c>" : string.Empty;
        writer.Line($"/// <remarks>{source}{version}.</remarks>");
    }

    private static string Global(TokenTable table)
    {
        return $"global::{table.Namespace}.{table.Name}";
    }

    private static string ResolvedGlobal(TokenTable table, string resolved)
    {
        return $"global::{table.Namespace}.{resolved}";
    }

    private static string OverridesGlobal(TokenTable table)
    {
        return $"global::{table.Namespace}.{OverridesName(table)}";
    }

    /// <summary>
    /// <c>ButtonColorTokens</c> becomes <c>ButtonColorOverrides</c> — the trailing "Tokens" would
    /// only add noise next to "Overrides".
    /// </summary>
    private static string OverridesName(TokenTable table)
    {
        var stem = table.Name.EndsWith("Tokens", StringComparison.Ordinal)
            ? table.Name.Substring(0, table.Name.Length - "Tokens".Length)
            : table.Name;

        return stem + "Overrides";
    }

    private static string Camel(string name)
    {
        return char.ToLowerInvariant(name[0]) + name.Substring(1);
    }
}
