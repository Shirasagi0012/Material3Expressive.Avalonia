using Material3Expressive.TokenGenerator.Model;
using System;
using System.Collections.Generic;

namespace Material3Expressive.TokenGenerator.Emit;

/// <summary>Turns raw token tables and system records into C#.</summary>
/// <remarks>
/// A <c>tokenSet</c> becomes the equivalent of an internal upstream <c>*Tokens</c> object. The
/// one record-shaped system table, <c>TypeScale</c>, remains a public system contract because the
/// typography scheme consumes it directly. Component default assembly belongs to component-owned
/// C# Defaults and is intentionally not generated here.
/// </remarks>
internal static class TableEmitter
{
    public static string Emit(TokenTable table)
    {
        var writer = new CodeWriter();
        Header(writer, table);

        writer.Line($"namespace {table.Namespace};");
        writer.Line();

        if (table.IsTokenSet)
            TokenSet(writer, table);
        else
            SystemRecord(writer, table);

        return writer.ToString();
    }

    private static void Header(CodeWriter writer, TokenTable table)
    {
        writer.Line("// <auto-generated />");
        writer.Line($"// Generated from the {table.Name} token table by Material3Expressive.TokenGenerator.");

        if (table.Source is { } source)
            writer.Line($"// Source: {source}");

        if (table.Version is { } version)
            writer.Line($"// Token DB: {version}");

        writer.Line($"// Provenance: {TokenProvenances.ToText(table.Provenance)}");

        writer.Line("#nullable enable");
        writer.Line();
    }

    private static void TokenSet(CodeWriter writer, TokenTable table)
    {
        writer.Doc("summary", table.Summary ?? $"The {table.Name} token set.");
        Provenance(writer, table);

        // Raw tables are implementation/provenance artifacts. Same-assembly component Defaults
        // may consume them, but they are not a package customization API.
        using (writer.Block($"internal static class {table.Name}"))
        {
            var first = true;
            foreach (var token in table.Tokens)
            {
                if (!first)
                    writer.Line();

                first = false;

                writer.Doc("summary", token.Summary);
                var modifier = TokenTypes.IsConstant(token.Type) ? "const" : "static readonly";
                writer.Line($"public {modifier} {TokenTypes.ToClrType(token.Type, token.EnumType)} {token.Name} = {token.Expression};");
            }
        }

        writer.Line();
        TokenDescriptors(writer, table);
        writer.Line();
        TokenOverrides(writer, table);
    }

    private static void TokenDescriptors(CodeWriter writer, TokenTable table)
    {
        writer.Doc("summary", $"Strongly typed resource keys for the {table.Name} token set.");
        Provenance(writer, table);

        using (writer.Block($"public static class {table.Name}Keys"))
        {
            var first = true;
            foreach (var token in table.Tokens)
            {
                if (!first)
                    writer.Line();

                first = false;
                writer.Doc("summary", token.Summary);
                writer.Line(
                    $"public static readonly {DescriptorType(token)} {token.Name} = new(\"{table.DescriptorPath(token.Name)}\", " +
                    $"global::MaterialDesignTokens.Avalonia.TokenLayer.{table.Layer});");
            }
        }
    }

    private static string DescriptorType(TokenEntry token)
    {
        return $"global::MaterialDesignTokens.Avalonia.MaterialToken<{DescriptorValueType(token)}>";
    }

    private static string DescriptorValueType(TokenEntry token)
    {
        return token.Type == TokenType.Color
            ? "global::Avalonia.Media.Color"
            : TokenTypes.ToClrType(token.Type, token.EnumType);
    }

    private static void TokenOverrides(CodeWriter writer, TokenTable table)
    {
        var enumConverters = EnumConverters(table);
        writer.Doc("summary", $"Sparse resource overrides for the {table.Name} token set.");
        using (writer.Block(
                   $"public sealed class {table.Name}Overrides : global::Material3Expressive.Foundation.Tokens.Runtime.MaterialTokenOverrides"))
        {
            var first = true;
            foreach (var token in table.Tokens)
            {
                if (!first)
                    writer.Line();

                first = false;
                writer.Doc("summary", token.Summary);
                writer.Line(
                    $"[global::System.ComponentModel.TypeConverter(typeof({DescriptorConverterType(token, enumConverters)}))]");
                var definition =
                    $"global::MaterialDesignTokens.Avalonia.TokenDefinition<{DescriptorValueType(token)}>";
                using (writer.Block($"public {definition}? {token.Name}"))
                {
                    writer.Line($"get => GetDefinition({table.Name}Keys.{token.Name});");
                    writer.Line(
                        $"set {{ if (value is null) Clear({table.Name}Keys.{token.Name}); else SetDefinition({table.Name}Keys.{token.Name}, value); }}");
                }
            }

            foreach (var converter in enumConverters)
            {
                writer.Line();
                writer.Doc("summary", $"Converts XAML literals of <c>{converter.Key}</c> to token definitions.");
                using (writer.Block(
                           $"public sealed class {converter.Value} : " +
                           "global::Material3Expressive.Foundation.Tokens.RawTokenDefinitionTypeConverter<" +
                           $"{converter.Key}>"))
                {
                }
            }
        }
    }

    private static IReadOnlyDictionary<string, string> EnumConverters(TokenTable table)
    {
        var result = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var token in table.Tokens)
        {
            if (token.Type != TokenType.Enum)
                continue;

            var valueType = DescriptorValueType(token);
            if (!result.ContainsKey(valueType))
                result.Add(valueType, $"EnumTokenDefinitionTypeConverter{result.Count}");
        }

        return result;
    }

    private static string DescriptorConverterType(
        TokenEntry token,
        IReadOnlyDictionary<string, string> enumConverters)
    {
        const string tokens = "global::Material3Expressive.Foundation.Tokens.";
        return token.Type switch
        {
            TokenType.Color => tokens + "RawColorTokenDefinitionTypeConverter",
            TokenType.Shape => tokens + "RawShapeTokenDefinitionTypeConverter",
            TokenType.Typography => tokens + "RawTypographyTokenDefinitionTypeConverter",
            TokenType.Motion => tokens + "RawMotionTokenDefinitionTypeConverter",
            TokenType.Boolean => tokens + "RawBooleanTokenDefinitionTypeConverter",
            TokenType.Enum => enumConverters[DescriptorValueType(token)],
            _ => tokens + "RawDoubleTokenDefinitionTypeConverter"
        };
    }

    private static void SystemRecord(CodeWriter writer, TokenTable table)
    {
        if (table.VariantEnum is { } enumName)
        {
            writer.Doc("summary", table.VariantEnumSummary ?? $"The variants {table.Name} is defined for.");
            using (writer.Block($"public enum {enumName}"))
            {
                for (var i = 0; i < table.Sets.Count; i++)
                {
                    var set = table.Sets[i];
                    writer.Doc("summary", set.Summary);
                    writer.Line(i == table.Sets.Count - 1 ? set.Name : set.Name + ",");
                }
            }

            writer.Line();
        }

        writer.Doc("summary", table.Summary ?? $"The {table.Name} system token values.");
        Provenance(writer, table);

        writer.Line($"public sealed partial record {table.Name}(");
        using (writer.Indent())
        {
            for (var i = 0; i < table.Properties.Count; i++)
            {
                var property = table.Properties[i];
                var comma = i == table.Properties.Count - 1 ? string.Empty : ",";
                writer.Line($"{TokenTypes.ToClrType(property.Type, property.EnumType)} {property.Name}{comma}");
            }
        }

        writer.Line(")");
        using (writer.Block(string.Empty))
        {
            for (var i = 0; i < table.Sets.Count; i++)
            {
                var set = table.Sets[i];
                if (i > 0)
                    writer.Line();

                writer.Doc("summary", set.Summary ?? $"The {set.Name} {table.Name}.");
                writer.Line($"public static {table.Name} {set.Name} {{ get; }} = new(");
                using (writer.Indent())
                {
                    for (var p = 0; p < table.Properties.Count; p++)
                    {
                        var property = table.Properties[p];
                        var comma = p == table.Properties.Count - 1 ? ");" : ",";
                        writer.Line($"{set.Values[property.Name].Expression}{comma}");
                    }
                }
            }

            if (table.VariantEnum is { } variantEnum)
            {
                writer.Line();
                writer.Doc("summary", "The token values for one variant.");
                using (writer.Block($"public static {table.Name} For({variantEnum} variant)"))
                {
                    writer.Line("return variant switch");
                    using (writer.Block(string.Empty, "};"))
                    {
                        foreach (var set in table.Sets)
                            writer.Line($"{variantEnum}.{set.Name} => {set.Name},");

                        writer.Line($"_ => {table.Sets[0].Name}");
                    }
                }
            }
        }
    }

    private static void Provenance(CodeWriter writer, TokenTable table)
    {
        if (table.Source is null && table.Version is null)
        {
            writer.Line($"/// <remarks>Provenance <c>{TokenProvenances.ToText(table.Provenance)}</c>.</remarks>");
            return;
        }

        var source = table.Source is { } s ? $"Transcribed from {s}" : "Transcribed from androidx";
        var version = table.Version is { } v ? $", token-DB stamp <c>{v}</c>" : string.Empty;
        var provenance = $", provenance <c>{TokenProvenances.ToText(table.Provenance)}</c>";
        writer.Line($"/// <remarks>{source}{version}{provenance}.</remarks>");
    }
}
