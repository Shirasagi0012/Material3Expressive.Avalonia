namespace Material3Expressive.Foundation;

/// <summary>Whether a bottom sheet is modal or embedded in its surrounding surface.</summary>
public enum BottomSheetVariant
{
    Modal,
    Standard
}

/// <summary>The compact inverted tooltip or the richer elevated tooltip treatment.</summary>
public enum TooltipVariant
{
    Plain,
    Rich
}

/// <summary>Whether a navigation drawer floats over content or shares its surface.</summary>
public enum DrawerVariant
{
    Modal,
    Standard
}

/// <summary>The neutral or vibrant floating-toolbar colour treatment.</summary>
public enum FloatingToolbarVariant
{
    Standard,
    Vibrant
}
