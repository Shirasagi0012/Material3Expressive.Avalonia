namespace Material3Expressive.Foundation;

/// <summary>Whether a badge is a dot or carries a count.</summary>
public enum BadgeVariant { Small, Large }

/// <summary>Whether a carousel shows several browsable items or a hero item.</summary>
public enum CarouselVariant { MultiBrowse, Hero }

/// <summary>Whether a loading indicator owns a container behind its morphing shape.</summary>
public enum LoadingIndicatorVariant { Standard, Contained }

/// <summary>Whether picker metrics are for the date or time picker.</summary>
public enum PickerVariant { Date, Time }

/// <summary>Whether progress is drawn along a line or around a circle.</summary>
public enum ProgressIndicatorShape { Linear, Circular }

/// <summary>The four Material chip meanings.</summary>
public enum ChipVariant { Assist, Filter, Input, Suggestion }
