<script setup lang="ts">
import { computed, ref, watch, onMounted, onUnmounted } from 'vue'
const props = defineProps<{
  label: string
  width: number
  height: number
  zoom: number
  scrollPosition: { left: number; top: number }
  src?: string
  pixels?: Uint8ClampedArray
  regions: number[][]
}>()
const emit = defineEmits<{
  pixel: [x: number, y: number, pin: boolean]
  scroll: [position: { left: number; top: number }]
}>()
const canvas = ref<HTMLCanvasElement>()
const viewport = ref<HTMLDivElement>()
let lastPosition = { left: 0, top: 0 }
function applyScroll() {
  if (!viewport.value) return
  viewport.value.scrollLeft = props.scrollPosition.left
  viewport.value.scrollTop = props.scrollPosition.top
  // Ignore the scroll events generated by synchronization, including clamping.
  lastPosition = {
    left: viewport.value.scrollLeft,
    top: viewport.value.scrollTop,
  }
}
function scroll() {
  if (!viewport.value) return
  const position = {
    left: viewport.value.scrollLeft,
    top: viewport.value.scrollTop,
  }
  if (position.left === lastPosition.left && position.top === lastPosition.top)
    return
  lastPosition = position
  emit('scroll', position)
}
watch(() => props.scrollPosition, applyScroll, { flush: 'post' })
const available = ref({ width: 0, height: 0 })
const scale = computed(
  () =>
    props.zoom ||
    Math.min(
      1,
      available.value.width / props.width,
      available.value.height / props.height,
    ),
)
const observer = new ResizeObserver(([entry]) => {
  if (entry)
    available.value = {
      width: entry.contentRect.width,
      height: entry.contentRect.height,
    }
})
function draw() {
  if (!canvas.value) return
  const ctx = canvas.value.getContext('2d')!
  canvas.value.width = props.width
  canvas.value.height = props.height
  if (props.pixels) {
    const image = ctx.createImageData(props.width, props.height)
    image.data.set(props.pixels)
    ctx.putImageData(image, 0, 0)
  }
  ctx.strokeStyle = '#d43890'
  ctx.lineWidth = 1
  for (const [x, y, w, h] of props.regions)
    ctx.strokeRect(x! + 0.5, y! + 0.5, Math.max(0, w! - 1), Math.max(0, h! - 1))
}
watch(() => [props.width, props.height, props.pixels, props.regions], draw, {
  flush: 'post',
})
onMounted(() => {
  draw()
  applyScroll()
  if (viewport.value) observer.observe(viewport.value)
})
onUnmounted(() => observer.disconnect())
function inspect(event: MouseEvent, pin: boolean) {
  const rect = canvas.value!.getBoundingClientRect()
  emit(
    'pixel',
    Math.floor(((event.clientX - rect.left) * props.width) / rect.width),
    Math.floor(((event.clientY - rect.top) * props.height) / rect.height),
    pin,
  )
}
</script>
<template>
  <figure>
    <figcaption>{{ label }}</figcaption>
    <div
      ref="viewport"
      class="image-scroll"
      :class="{ 'fit-image': !zoom }"
      tabindex="0"
      role="region"
      :aria-label="label + ' preview'"
      @scroll="scroll"
    >
      <div
        class="raster-layers"
        :style="{ width: width * scale + 'px', height: height * scale + 'px' }"
      >
        <img v-if="src" :src="src" :alt="label" /><canvas
          ref="canvas"
          :aria-label="label + ' raster'"
          @mousemove="inspect($event, false)"
          @click="inspect($event, true)"
        />
      </div>
    </div>
  </figure>
</template>
